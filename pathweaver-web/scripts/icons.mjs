// Collect every Iconify name used in src/ and vendor/tweeq, plus PathWeaver's
// own tool SVGs, into one offline module. No icon is fetched at runtime.
import {readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs'
import {join, dirname} from 'node:path'
import {fileURLToPath} from 'node:url'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sets = {
  mdi: JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json/mdi/icons.json'))),
  'material-symbols': JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json/material-symbols/icons.json'))),
}
const used = new Set()
const walk = dir => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) { if (f !== 'node_modules') walk(p); continue }
    if (!/\.(vue|ts)$/.test(f) || f.endsWith('.generated.ts')) continue
    for (const m of readFileSync(p, 'utf8').matchAll(/['"`](mdi|material-symbols):([a-z0-9-]+)['"`]/g)) used.add(`${m[1]}:${m[2]}`)
  }
}
walk(join(root, 'src'))
walk(join(root, 'vendor/tweeq/src'))
const out = {}
const missing = []
for (const name of [...used].sort()) {
  const [prefix, icon] = name.split(':')
  const set = sets[prefix]
  const id = set.icons[icon] ? icon : set.aliases?.[icon]?.parent
  const data = id && set.icons[id]
  if (!data) { missing.push(name); continue }
  out[name] = {body: data.body, width: data.width ?? set.width ?? 24, height: data.height ?? set.height ?? 24}
}
const toolDir = join(root, 'assets/tools')
for (const f of readdirSync(toolDir).filter(f => f.endsWith('.svg'))) {
  const svg = readFileSync(join(toolDir, f), 'utf8')
  const vb = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number)
  const attrs = svg.match(/<svg([^>]*)>/)[1].replace(/\s(xmlns|viewBox)="[^"]*"/g, '')
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  const body = `<g${attrs}>${inner}</g>`.replace(/"white"/g, '"currentColor"')
  out[`pw:${f.replace('.svg', '')}`] = {body, width: vb[2], height: vb[3]}
}
if (missing.length) console.warn('missing icons:', missing.join(', '))
writeFileSync(join(root, 'src/icons.generated.ts'),
  `// Generated by scripts/icons.mjs — do not edit.\nimport {addIcon} from '@iconify/vue'\nconst icons: Record<string, {body: string; width: number; height: number}> = ${JSON.stringify(out)}\nfor (const [name, data] of Object.entries(icons)) addIcon(name, data)\n`)
console.log(`icons: ${Object.keys(out).length}`)
